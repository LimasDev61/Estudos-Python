# Tipos int e float

# int -> inteiro
# o tipo int representa um número inteiro positivo ou negativo

# float -> real
# o tipo float representa um número real positivo ou negativo
# float pode ser usado para representar valores com casas decimais - pontos flutuantes

# A função type mostra o tipo que o Python inferiu ao valor

# Tipos int:
print(10)
print(-10)

# Tipos Float:
print(3.14)
print(-3.14)

# Observação: quando um float tem um ponto flutuante, ele sempre se torna um float

# A classe Type para verificar os tipos dos valores
print(type(10))
print(type(10.0))
print(type("10"))
