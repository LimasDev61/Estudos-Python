"""

Operadores Relacionais de Comparação
===============================================================================

OP.........Significado.........Exemplo

>..........Maior...............5 > 2  (Verdadeiro)
<..........Menor...............5 < 2  (Falso)
>=.........Maior ou Igual......5 >= 2 (Verdadeiro)
<=.........Menor ou Igual......5 <= 2 (Falso)
==.........Igual...............5 == 2 (Falso)
!=.........Diferente..........5 != 2 (Verdadeiro)

"""

# Exemplos de uso dos operadores relacionais

maior = 5 > 2
menor = 5 < 2
maior_ou_igual = 5 >= 2
menor_ou_igual = 5 <= 2
igual = 5 == 2
diferente = 5 != 2

print("5 > 2:", maior)                   # Verdadeiro
print("5 < 2:", menor)                   # Falso
print("5 >= 2:", maior_ou_igual)         # Verdadeiro
print("5 <= 2:", menor_ou_igual)         # Falso     
print("5 == 2:", igual)                  # Falso
print("5 != 2:", diferente)              # Verdadeiro