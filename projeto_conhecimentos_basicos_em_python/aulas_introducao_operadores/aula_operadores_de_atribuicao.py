# Operadores de Atribuição
# = += -= *= /= //= **= %=

contador = int(input("Digite um número: "))

contador += 1   
print(contador)

contador *= 10  
print(contador)

contador /= 2  
print(contador)

contador -= 10  
print(contador)

contador //= 3  
print(contador)

contador **= 2 
print(contador)

contador %= 7 
print(contador)

# Operadores de Atribuição com strings
nome = "Geek"

nome += " University"  
print(nome)

nome *= 3  
print(nome)

# Operadores de Atribuição com listas
lista = [1, 2, 3]

