# Adição
print("Adição:", 10 + 10)

# Subtração
print("Subtração:", 10 - 9)

# Multiplicação
print("Multiplicação:", 10 * 10)

# Divisão
print("Divisão:", 10 / 2.2)

# Divisão Inteira (Truncamento)
print("Divisão Inteira:", 11 // 10)

# Resto da Divisão
print("Resto da Divisão:", 10 % 9)

# Potência
print("Potência:", 10 ** 10)

# Observação, sempre que fazemos um calculo com um float, ele sempre se torna um float, com exceção da divisão para inteiros