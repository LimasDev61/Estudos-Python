# Tipo de dado bool (booleano)
# Ao questionar algo em um programa,
# só existem duas repostas possíveis:
# sim (True) ou nao (False).
# Existem vários operadores para "questionar",
# como: ==, !=, >, <, >=, <=, is e in.

# Exemplos
print(10 == 10)
print(10 != 10)
print(10 > 10)
print(10 < 10)
print(10 >= 10)
print(10 <= 10)
print(10 is 10)
print(10 in [1, 2, 3])

print("\nStrings: ")
# Exemplos string
print(bool("Olá"))
print(bool(""))
print(type("Ola") is str)

# Type
print(type(True))
print(type(False))

